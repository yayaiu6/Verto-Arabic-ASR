import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {copyDependencySources} from './dependency-sources.mjs';
const output=path.resolve('dist');
if(output!==path.join(process.cwd(),'dist'))throw new Error('Unexpected build path');
await fs.rm(output,{recursive:true,force:true});
await fs.mkdir(output,{recursive:true});
await fs.cp('web',path.join(output,'web'),{recursive:true});
await fs.cp('public',output,{recursive:true});
await fs.cp('licenses',path.join(output,'licenses'),{recursive:true});
const sourceCache=path.resolve('node_modules/.cache/verto-dependency-sources');
await copyDependencySources(sourceCache);
await fs.cp(sourceCache,path.join(output,'licenses','sources'),{recursive:true});
await fs.copyFile('LICENSE',path.join(output,'LICENSE'));
await fs.copyFile('THIRD_PARTY_NOTICES.md',path.join(output,'THIRD_PARTY_NOTICES.md'));
await fs.mkdir(path.join(output,'runtime','1.23.2'),{recursive:true});
for(const name of ['ort.webgpu.min.mjs','ort-wasm-simd-threaded.jsep.mjs','ort-wasm-simd-threaded.jsep.wasm','ort-wasm-simd-threaded.asyncify.mjs','ort-wasm-simd-threaded.asyncify.wasm'])await fs.copyFile('node_modules/onnxruntime-web/dist/'+name,path.join(output,'runtime','1.23.2',name));
for(const [source,target]of [['node_modules/@ffmpeg/ffmpeg/dist/esm','ffmpeg/0.12.15/wrapper'],['node_modules/@ffmpeg/core/dist/esm','ffmpeg/0.12.10/core']])await fs.cp(source,path.join(output,target),{recursive:true,filter:p=>!p.endsWith('.ts')});
await fs.writeFile(path.join(output,'index.html'),'<!doctype html><meta http-equiv="refresh" content="0;url=/web/index.html"><a href="/web/index.html">Verto Arabic ASR</a>');
const shell=['/','/index.html','/web/index.html','/config.json',... (await fs.readdir('web')).map(n=>'/web/'+n),'/LICENSE','/THIRD_PARTY_NOTICES.md'];
await fs.writeFile(path.join(output,'precache.json'),JSON.stringify([...new Set(shell)]));
const hash=createHash('sha256');
for(const file of [...await fs.readdir('web')].sort())hash.update(await fs.readFile(path.join('web',file)));
hash.update(await fs.readFile('package-lock.json'));hash.update(await fs.readFile('public/sw.js'));hash.update(await fs.readFile('public/config.json'));
const version=hash.digest('hex').slice(0,20);
await fs.writeFile(path.join(output,'sw.js'),(await fs.readFile('public/sw.js','utf8')).replace('__BUILD_VERSION__',version));
console.log('Static build ready in dist/; no model or conversion source copied.');
